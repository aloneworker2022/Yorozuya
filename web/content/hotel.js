function shuffleCopy(arr) {
  const a = (arr || []).slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function pickFresh(list, lastIds, n) {
  const unused = (list || []).filter((x) => !lastIds.includes(x.id));
  const bag = shuffleCopy(unused.length ? unused : list || []);
  return bag.slice(0, n).map((x) => ({ ...x }));
}

export function hotelAdvanceAct(zone) {
  const gos = HOTEL_MENU[zone]?.go || [];
  const adv = gos[0];
  if (!adv) return null;
  return { ...adv };
}

export function hotelGoActs(zone) {
  return (HOTEL_MENU[zone]?.go || []).map((x) => ({ ...x }));
}

/** 每區 4～5 個選項：設施互動＋羞辱玩家＋換場。私密區才有插入。 */
export function listHotelChoices(zone, { lastIds = [], stayBeats = 0, preferNtr = true } = {}) {
  const z = zone || "parking";
  const menu = HOTEL_MENU[z] || HOTEL_MENU.bed;
  const allowSex = hotelPrivateSex(z);
  const acts = [];
  acts.push(...pickFresh(menu.interact, lastIds, allowSex ? 1 : 2));
  if (allowSex) acts.push(...pickFresh(menu.sex, lastIds, 1));
  if (preferNtr !== false) acts.push(...pickFresh(menu.ntr, lastIds, 1));
  const gos = hotelGoActs(z);
  if (gos.length) {
    const goPick = stayBeats >= 1
      ? gos
      : gos.filter((g) => g.dest === "corridor" || g.dest === "bed" || gos.length <= 2);
    const bag = shuffleCopy(goPick.length ? goPick : gos);
    acts.push({ ...bag[0] });
    if (stayBeats >= 2 && bag[1]) acts.push({ ...bag[1] });
  }
  const seen = new Set();
  const out = acts.filter((x) => {
    if (!x || seen.has(x.id)) return false;
    seen.add(x.id);
    return true;
  });
  return out.slice(0, 5);
}

export function parseHotelChoice(raw, choices) {
  const list = choices || [];
  if (!list.length) return null;
  const t = String(raw || "");
  const m = t.match(/選\s*([1-9])|選項\s*([1-9])|指令\s*[:：]\s*(?:選\s*)?([1-9])/);
  const n = Number(m?.[1] || m?.[2] || m?.[3] || 0);
  if (n >= 1 && n <= list.length) return list[n - 1];
  for (const c of list) {
    const name = String(c.name || "");
    if (name && t.includes(name)) return c;
  }
  return null;
}
