function isHotelInsert(act) {
  const cmd = String(act?.cmd || "");
  const name = String(act?.name || "");
  const how = String(act?.how || "");
  if (/射|插|幹|騎乘/.test(name) || /插入|抽插|再幹|整根/.test(how)) return true;
  return !/^(親|脫|摸|舔|吸|掀)\s/.test(cmd);
}

export function pickHotelAct(zone, { lastIds = [], preferNtr = false, fresh = false } = {}) {
  const all = hotelActsOf(zone);
  if (!all.length) return null;
  let bag = all;
  if (fresh) {
    const openers = all.filter((x) => !x.ntr && !isHotelInsert(x));
    if (openers.length) bag = openers;
  } else if (preferNtr || Math.random() < 0.22) {
    const ntr = all.filter((x) => x.ntr);
    if (ntr.length) bag = ntr;
  }
  const unused = bag.filter((x) => !lastIds.includes(x.id));
  if (unused.length) bag = unused;
  return { ...bag[Math.floor(Math.random() * bag.length)] };
}

