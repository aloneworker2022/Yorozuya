export function flattenTags(...chunks) {
  const seen = new Set();
  const out = [];
  for (const chunk of chunks) {
    for (const t of String(chunk || "").split(",")) {
      const b = t.trim();
      if (b && !seen.has(b.toLowerCase())) {
        seen.add(b.toLowerCase());
        out.push(b);
      }
    }
  }
  return out.join(", ");
}

function ageTag(age) {
  const a = parseInt(age, 10);
  if (!Number.isFinite(a)) return "";
  return a <= 22 ? "young adult" : "mature female";
}

/** 口交／大頭特寫用人設：臉、眼、嘴、髮。不含胸／性器／衣服。 */
export function headTagsFromLook(look = {}, specialTraits = [], opts = {}) {
  const skipClosedEyes = opts.skipClosedEyes !== false;
  const over = new Set();
  const extra = [];
  for (const t of specialTraits || []) {
    const name = (t && t.name) || t;
    const hit = HEAD_SPECIAL[name];
    if (hit) {
      extra.push(hit.tags);
      for (const k of hit.over || []) over.add(k);
    }
  }
  const pick = (table, key) => (over.has(key) ? "" : (table[look[key]] || ""));
  let eyes = pick(EYES, "eyes");
  if (skipClosedEyes && /\bclosed eyes\b/i.test(eyes)) eyes = "";
  return flattenTags(
    ageTag(look.age),
    pick(FACE, "face"),
    eyes,
    pick(EYE_COLOR, "eye_color"),
    pick(MOUTH, "mouth"),
    pick(HAIR_COLOR, "hair_color"),
    pick(HAIR, "hair"),
    pick(FEATURE, "feature"),
    ...extra,
  );
}
