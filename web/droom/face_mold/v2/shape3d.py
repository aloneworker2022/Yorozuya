# 臉模 v2 的簡單 3D（turn45.py、features.py 共用）：參考圖座標，x 往她左邊、y 往下、z 往前，原點＝頭蓋圓心
import math
RR=75.5;CYR=499.5;BACK=1.08
def lerp_tab(tab,y):
  if y<=tab[0][0]:return tab[0][1]
  for (y0,v0),(y1,v1) in zip(tab,tab[1:]):
    if y0<=y<=y1:return v0+(v1-v0)*(y-y0)/(y1-y0)
  return tab[-1][1]
# 正面：下半臉的半寬（和 outline.py 同一張表）
# 兩頰（使用者紅線）：從眉線（圓上）直線斜到鼻線，再收到下巴
JAW=[(505,75.3),(519,72.9),(538,64.7),(557,56.6),(577,48),(582,45),(595,32),(607,17),(613,6),(614.5,1)]
# 側臉中線（z＝322－x）：有鼻子的那條、和把鼻子拉平的那條（臉頰用）
PROF=[(520,250),(532,253),(545,256),(554,250),(562,242),(567,238),(573,243),(576,247),(578.6,245.4),(581.2,242.4),(583.4,243.2),(587.5,249),(593,249),(598,254),(604,256),(610,258),(613,264),(614.5,270)]
FLAT=[(520,250),(532,253),(545,256),(577,250),(582,247),(588,250),(593,251),(598,254),(604,256),(610,258),(613,264),(614.5,270)]
zp=lambda y:322-lerp_tab(PROF,y)
zc=lambda y:322-lerp_tab(FLAT,y)
# 轉過去時（斜臉）的鼻子：凸出量 ×NK、整組往前 NF；側臉不用這個
import os
NK=float(os.environ.get('NK','1'))
# 整個鼻子（山根→鼻頭→鼻底）一起往前推 NF（參考圖像素；使用者 2026-11-19：是整組往前移，不是只拉長鼻尖）
NF=float(os.environ.get('NF','0'))   # 0＝不改形狀（使用者：只要整組往前移，見 features.py NX）
def _nfw(y):return max(0,min(1,(y-538)/6,(580-y)/4))
def znose(y):return max(0,zp(y)-zc(y))*NK+NF*_nfw(y)
NW=5   # 鼻子的寬（中線左右各幾格，參考圖像素）
# 下顎底（側臉：下巴底 → 下顎角）：這幾列的切面後緣
JAWB=[(593,4),(594,4),(601,12),(609,32),(612,46),(613,58),(614.5,52)]
def zb(y):return lerp_tab(JAWB,y) if y>=593 else 2
# 最寬處的深度：眼線以上在圓心，鼻線以下往前收（V 臉在 45° 才會從耳下斜到下巴）
ZW=[(545,0),(560,6),(577,16),(595,30),(607,44),(613,56),(614.5,60)]
zw=lambda y:lerp_tab(ZW,y)

def surf(x,y):
  # 臉表面的深度（正面看過去那一面）：頭蓋球、下半臉前半橢圓＋中間的鼻子，取大的
  z=-1e9;dy=y-CYR
  if x*x+dy*dy<RR*RR:z=math.sqrt(RR*RR-x*x-dy*dy)
  if 505<=y<=614.5:
    w=lerp_tab(JAW,y)
    if abs(x)<w:
      zm=zw(y);f=zc(y);v=zm+(f-zm)*math.sqrt(1-(x/w)**2)+znose(y)*max(0,1-abs(x)/NW)
      z=max(z,v)
  return z
