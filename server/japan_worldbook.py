def lookup(ground_id="", destination=""):
    # Unknown destinations must never silently borrow the home town.
    key = TRAVEL_IDS.get(destination, destination) if destination else ground_id
    return PLACES.get(key)


def context(ground_id="", destination="", at=0):
    place = lookup(ground_id, destination)
    if not place:
        return LIFE_RULE
    month = datetime.fromtimestamp(at / 1000, ZoneInfo("Asia/Tokyo")).month if at else 0
    season = (month % 12) // 3 if month else None
    # Stored order: spring, summer, autumn, winter.
    season_line = place["seasons"][(season - 1) % 4] if season is not None else "季節未提供，不預設花雪或祭典。"
    return "\n".join((f"【所在地世界書：{place['name']}】", place["landmarks"],
                      "飲食素材：" + place["food"], place["texture"],
                      "當季可能景象（不是今日天氣）：" + season_line, place["transit"], LIFE_RULE))
